// v0.3 campaign coverage record (Claude, 2026-10-16). Reads the served co-op
// maps (the v0.2 build; v0.3 changes no map) and counts, per source map, the
// entity families whose state the v0.3 map state (native/rc4/state-runtime.hpp)
// keeps across revisits and saves, and the ones it deliberately keeps as served.
// Usage: audit-v03.mjs MAP_BUILD_DIR OUTPUT_MARKDOWN
import fs from 'node:fs';
import path from 'node:path';
import {decodeBsp} from './bsp.mjs';

export const sourceOf=map=>map.replace(/_e\d+$/,'');
const v=(e,k)=>e.pairs.find(p=>p[0]===k)?.[1];
const cls=e=>v(e,'classname')??'';
const KEEP=new Set(['info_player_start','info_player_deathmatch','info_player_coop','info_landmark','info_teleport_destination','trigger_changelevel','trigger_coop_changelevel','inter_door_coop_changelevel','inter_door_exit','cof_changelevel','cof_lobby_start']);

export function auditMap(entities){
 const exits=new Set(entities.filter(e=>cls(e)==='cof_changelevel').map(e=>v(e,'targetname')).filter(Boolean));
 const moveNames=new Set(entities.map(e=>v(e,'movewith')).filter(Boolean));
 const r={pickups:0,keyItems:[],locks:[],monsters:0,drowned:0,makers:0,onceTriggers:0,autoOnce:0,gates:0,lockToggles:0,codes:0,cameras:0,scripts:0,globals:0,endings:0,keptAsServed:0,moveWith:0,destinations:[]};
 for(const e of entities){
  const c=cls(e);
  if(/^(item_|weapon_|ammo_)/.test(c)&&c!=='item_padlock'&&!v(e,'target'))r.pickups++;
  if(c==='item_key'&&v(e,'message'))r.keyItems.push(path.basename(v(e,'message')));
  if(v(e,'lockedby'))r.locks.push(v(e,'lockedby'));
  if(c.startsWith('monster_')&&c!=='monster_generic')r.monsters++;
  if(c==='monster_crazybitch')r.drowned++;
  if(c==='monstermaker'||c==='squadmaker')r.makers++;
  if(c==='trigger_once'&&!exits.has(v(e,'target')))r.onceTriggers++;
  if(c==='trigger_auto'&&(Number(v(e,'spawnflags')??0)&1))r.autoOnce++;
  if(c==='multisource')r.gates++;
  if(c==='cof_interdooronoff')r.lockToggles++;
  if(/keypad|computer|passwordnote|addcodenote|padlock/.test(c))r.codes++;
  if(c==='trigger_camera')r.cameras++;
  if(c==='scripted_sequence'||c==='aiscripted_sequence')r.scripts++;
  if(c==='env_global')r.globals++;
  if(/ending|game_end/.test(c))r.endings++;
  if(v(e,'movewith')||moveNames.has(v(e,'targetname')))r.moveWith++;
  if(KEEP.has(c)||c.startsWith('cof_coop_spawn')||exits.has(v(e,'target')))r.keptAsServed++;
  if(c==='cof_changelevel'&&v(e,'message'))r.destinations.push(v(e,'message'));
 }
 return r;
}
export function markdown(rows){
 const head=['| Source map (aliases) | Exits to | Pickups | Key items (cards) / locks | Monsters (Drowned) / makers | Once-triggers / auto-once | Gates / lock toggles / code+puzzle | Cameras / scripts | env_global / endings | Kept as served (exits, starts) / movewith |','|---|---|---|---|---|---|---|---|---|---|'];
 const body=rows.map(([source,aliases,r])=>`| ${source} (${aliases}) | ${[...new Set(r.destinations.map(sourceOf))].sort().join(', ')||'-'} | ${r.pickups} | ${[...new Set(r.keyItems)].join(', ')||'-'} / ${[...new Set(r.locks)].join(', ')||'-'} | ${r.monsters} (${r.drowned}) / ${r.makers} | ${r.onceTriggers} / ${r.autoOnce} | ${r.gates} / ${r.lockToggles} / ${r.codes} | ${r.cameras} / ${r.scripts} | ${r.globals} / ${r.endings} | ${r.keptAsServed} / ${r.moveWith} |`);
 return [...head,...body].join('\n');
}
export function main([dir,out]){
 if(!dir||!out)throw Error('Usage: audit-v03.mjs MAP_BUILD_DIR OUTPUT_MARKDOWN');
 const groups=new Map();
 for(const f of fs.readdirSync(dir).filter(f=>/^s4_.*\.bsp$/.test(f)).sort()){
  const map=f.slice(0,-4),ents=decodeBsp(fs.readFileSync(path.join(dir,f))).entities,src=sourceOf(map);
  const g=groups.get(src)??{aliases:[],best:null,size:-1};g.aliases.push(map);if(ents.length>g.size){g.size=ents.length;g.best=auditMap(ents);}groups.set(src,g);
 }
 const rows=[...groups].map(([src,g])=>[src,g.aliases.length,g.best]);
 const total=k=>rows.reduce((n,[, ,r])=>n+(Array.isArray(r[k])?r[k].length:r[k]),0);
 const text=`Generated by scripts/audit-v03.mjs from ${path.basename(dir)}: ${rows.length} source maps, ${rows.reduce((n,[,a])=>n+a,0)} aliases. Counts are for the largest alias of each source map.\n\nTotals: pickups ${total('pickups')}, key items ${total('keyItems')}, locks ${total('locks')}, monsters ${total('monsters')} (Drowned ${total('drowned')}), monster makers ${total('makers')}, once-triggers ${total('onceTriggers')}, auto-once ${total('autoOnce')}, gates ${total('gates')}, lock toggles ${total('lockToggles')}, code/puzzle entities ${total('codes')}, cameras ${total('cameras')}, scripted sequences ${total('scripts')}, env_global ${total('globals')}, ending entities ${total('endings')}, kept as served ${total('keptAsServed')}, movewith ${total('moveWith')}.\n\n${markdown(rows)}\n`;
 fs.writeFileSync(out,text);return {sources:rows.length};
}
if(process.argv[1]&&path.resolve(process.argv[1])===path.resolve(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/,'$1')))console.log(main(process.argv.slice(2)));
